import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const drizzleDirectory = join(projectRoot, "drizzle");
const journal = JSON.parse(
  readFileSync(join(drizzleDirectory, "meta", "_journal.json"), "utf8"),
);

const migrations = Object.fromEntries(
  journal.entries.map((entry) => [
    `m${String(entry.idx).padStart(4, "0")}`,
    readFileSync(join(drizzleDirectory, `${entry.tag}.sql`), "utf8"),
  ]),
);

const output = `// Generated by scripts/bundle-drizzle-migrations.mjs. Do not edit manually.\nexport const bundledMigrationSql = ${JSON.stringify(migrations, null, 2)} as const;\n`;

writeFileSync(join(projectRoot, "db", "migrations.generated.ts"), output);
